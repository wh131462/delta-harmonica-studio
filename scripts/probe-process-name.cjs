const koffi = require('koffi');
const user32 = koffi.load('user32.dll');
const kernel32 = koffi.load('kernel32.dll');
const GetForegroundWindow = user32.func('void * __stdcall GetForegroundWindow()');
const GetWindowThreadProcessId = user32.func('uint32 __stdcall GetWindowThreadProcessId(void *h, _Out_ uint32 *pid)');
const OpenProcess = kernel32.func('void * __stdcall OpenProcess(uint32 access, bool inherit, uint32 pid)');
const QueryFullProcessImageNameW = kernel32.func('bool __stdcall QueryFullProcessImageNameW(void *h, uint32 flags, _Out_ char16_t *buf, _Inout_ uint32 *size)');
const CloseHandle = kernel32.func('bool __stdcall CloseHandle(void *h)');
const GetWindowTextW = user32.func('int __stdcall GetWindowTextW(void *h, void *buf, int max)');
const K32GetModuleFileNameExW = koffi.load('psapi.dll').func('uint32 __stdcall GetModuleFileNameExW(void *h, void *mod, void *buf, uint32 size)');

const hwnd = GetForegroundWindow();
const pidArr = [null];
const tid = GetWindowThreadProcessId(hwnd, pidArr);
console.log('tid', tid, 'pid', pidArr[0]);
const h = OpenProcess(0x1000, false, pidArr[0]);
console.log('handle', String(h));
const buf = Buffer.alloc(2048);
const size = [1024];
const ok = QueryFullProcessImageNameW(h, 0, buf, size);
console.log('query ok', ok, 'size', size[0], 'path', JSON.stringify(buf.subarray(0, size[0]*2).toString('utf16le')));
const modBuf = Buffer.alloc(2048);
const modLen = K32GetModuleFileNameExW(h, null, modBuf, 1024);
console.log('psapi len', modLen, JSON.stringify(modBuf.subarray(0, modLen*2).toString('utf16le')));
CloseHandle(h);
const tb = Buffer.alloc(1024);
const len = GetWindowTextW(hwnd, tb, 512);
console.log('title', JSON.stringify(tb.subarray(0, len*2).toString('utf16le')));
